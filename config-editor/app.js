/* Config Editor for the plugin's main config.yml.
 *
 * The whole file is held as one parsed JS object (state). Friendly forms edit
 * the commonly-tuned sections by mutating that object in place; any sections
 * the forms don't model (routing, quality.consumption, ...)
 * survive an upload untouched. Output is produced by YAMLLite.dump.
 */
"use strict";

const STORE_KEY = "config-editor-v2";
const OLD_STORE_KEY = "config-editor-v1";
const $ = (id) => document.getElementById(id);

function num(v, fallback) { const n = parseFloat(v); return isNaN(n) ? fallback : n; }
function clamp(v, lo, hi) { return Math.min(hi, Math.max(lo, v)); }

function defaultConfig() {
  return YAMLLite.parse(C4_DEFAULT_CONFIG_YAML);
}

const QUALITY_TIERS = ["poor", "decent", "good", "perfect"];

let state = load();

function load() {
  try {
    const raw = localStorage.getItem(STORE_KEY);
    if (raw) return JSON.parse(raw);
    const old = localStorage.getItem(OLD_STORE_KEY);
    if (old) {
      const migrated = mergeDefaults(defaultConfig(), JSON.parse(old));
      localStorage.setItem(STORE_KEY, JSON.stringify(migrated));
      return migrated;
    }
  } catch (e) { /* fall through */ }
  return defaultConfig();
}

function mergeDefaults(defaults, saved) {
  if (!defaults || typeof defaults !== "object" || Array.isArray(defaults)) {
    return saved === undefined ? defaults : saved;
  }
  if (!saved || typeof saved !== "object" || Array.isArray(saved)) return defaults;
  const merged = { ...defaults };
  for (const key of Object.keys(saved)) {
    merged[key] = key in defaults ? mergeDefaults(defaults[key], saved[key]) : saved[key];
  }
  return merged;
}

function save() {
  try { localStorage.setItem(STORE_KEY, JSON.stringify(state)); } catch (e) { /* full/blocked */ }
}

// Ensure a nested path exists, returning the leaf object.
function sect(...path) {
  let o = state;
  for (const k of path) { if (!o[k] || typeof o[k] !== "object") o[k] = {}; o = o[k]; }
  return o;
}

