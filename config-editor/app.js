function formatConfigYAML(config) {
  const out = [
    "# Generated by tools/config-editor",
    "# Drop into plugins/C4/config.yml",
  ];
  for (const line of YAMLLite.dump(config).trimEnd().split("\n")) {
    const match = /^([A-Za-z0-9_-]+):(?:\s|$)/.exec(line);
    const label = match ? CONFIG_SECTION_LABELS[match[1]] : null;
    if (label) {
      out.push("");
      out.push(`# ____________________ ${label} ____________________`);
    }
    out.push(line);
  }
  return out.join("\n") + "\n";
}

function renderYAML() {
  $("yaml-out").textContent = formatConfigYAML(state);
}

