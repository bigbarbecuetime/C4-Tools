function addGroup(obj, rootId, base, memberKeys) {
  let i = 1, name = base;
  while (obj[name] !== undefined) name = base + "_" + i++;
  obj[name] = [];
  buildGroups(rootId, obj, memberKeys); changed();
}

// Copy button is matched by selector (the shared `$` helper is id-only).
function bindCopy() {
  const btn = document.querySelector('[data-copy="yaml-out"]');
  if (!btn) return;
  btn.onclick = () => {
    navigator.clipboard.writeText($("yaml-out").textContent).then(() => {
      btn.classList.add("copied"); btn.textContent = "copied!";
      setTimeout(() => { btn.classList.remove("copied"); btn.textContent = "copy"; }, 1200);
    });
  };
}

